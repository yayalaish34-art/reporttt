"""Files: a local folder in development, a private Vercel Blob store when deployed.

A function's own disk is temporary, so nothing durable may live there. Client plans are
confidential, which is why the store is private and every read goes through the API's
own login check. Keys are generated by the server, or validated against a strict pattern
by the caller, and are never raw user input.
"""

import tempfile
import uuid
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path

from vercel.blob import sync as blob

from .config import settings

CHUNK_SIZE = 64 * 1024


class _LocalStorage:
    @staticmethod
    def _path(key: str) -> Path:
        return Path(settings.elf_storage_dir) / key

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def size(self, key: str) -> int | None:
        path = self._path(key)
        return path.stat().st_size if path.exists() else None

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def stream(self, key: str) -> Iterator[bytes]:
        with self._path(key).open("rb") as file:
            while chunk := file.read(CHUNK_SIZE):
                yield chunk

    @contextmanager
    def local_copy(self, key: str) -> Iterator[Path]:
        yield self._path(key)


class _BlobStorage:
    def put(self, key: str, data: bytes) -> None:
        # Overwriting only ever happens for a page rendered twice at once, with identical bytes.
        blob.put_blob(key, data, access="private", allow_overwrite=True)

    def size(self, key: str) -> int | None:
        try:
            return blob.head_blob(key).size
        except blob.BlobNotFoundError:
            return None

    def delete(self, key: str) -> None:
        blob.delete_blob(key)

    def stream(self, key: str) -> Iterator[bytes]:
        with blob.stream_blob(key, access="private") as download:
            yield from download

    @contextmanager
    def local_copy(self, key: str) -> Iterator[Path]:
        # Only /tmp is writable, and it may outlive the request on a reused instance.
        with tempfile.TemporaryDirectory(prefix="elf-") as folder:
            path = Path(folder) / Path(key).name
            with path.open("wb") as file:
                for chunk in self.stream(key):
                    file.write(chunk)
            yield path


_backend = _BlobStorage() if settings.uses_blob_storage else _LocalStorage()


def save(data: bytes, suffix: str, prefix: str = "files") -> str:
    key = f"{prefix}/{uuid.uuid4()}{suffix}"
    _backend.put(key, data)
    return key


def save_as(key: str, data: bytes) -> None:
    _backend.put(key, data)


def size(key: str) -> int | None:
    """The stored size in bytes, or None when no such file exists."""
    return _backend.size(key)


def exists(key: str) -> bool:
    return _backend.size(key) is not None


def delete(key: str) -> None:
    _backend.delete(key)


def stream(key: str) -> Iterator[bytes]:
    return _backend.stream(key)


def local_copy(key: str):
    """A path for the libraries that need one. Valid only inside the `with` block."""
    return _backend.local_copy(key)
