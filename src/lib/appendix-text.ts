/**
 * Appendix ח — the recommendation for a periodic survey.
 *
 * The appendix argues why a survey should be repeated, and the argument is not the same
 * everywhere. A workplace turns on the employer's duty of care and on the Work Safety
 * Ordinance; a home turns on precaution and on where people sleep; a school turns on
 * children, who are neither employees nor householders. The template carried the
 * workplace version alone, so a family that had their flat surveyed received a page
 * about their employer's statutory obligations.
 *
 * Written per site character rather than assembled from shared fragments. The passages
 * overlap in shape, not in wording, and a template that stitched them from parts would
 * produce the kind of prose nobody signs.
 */

