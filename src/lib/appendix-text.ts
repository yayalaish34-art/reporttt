/**
 * The appendix for a site character.
 *
 * Keyed by the values of `SITE_CHARACTER_OPTIONS`. Anything else — a character typed by
 * hand through the "אחר" box, or a report written before the list existed — gets the
 * workplace text, which is what every report carried until now: unchanged behaviour for
 * whatever the mapping does not recognise, rather than a blank appendix.
 */
export function appendixForSite(siteCharacter: string): AppendixText {
  const character = siteCharacter.trim();
  // Both spellings of the government option, so a report written before the rename
  // still gets the government appendix rather than the workplace one.
  if ((GOVERNMENT_SITE_ALIASES as readonly string[]).includes(character)) return GOVERNMENT_HOUSING;
  switch (character) {
    case 'מגורים':
      return RESIDENTIAL;
    case 'מוסדות חינוך':
      return EDUCATIONAL;
    default:
      return WORKPLACE;
  }
}
